package ru.saydov.emc.world;

import org.bukkit.World;
import org.bukkit.entity.Player;
import org.jetbrains.annotations.Nullable;
import ru.saydov.emc.exception.InvalidWorldNameException;
import ru.saydov.emc.exception.WorldAlreadyExistsException;
import ru.saydov.emc.exception.WorldDeletionException;
import ru.saydov.emc.exception.WorldNotFoundException;

import java.util.List;

/**
 * Сервис управления пустыми мирами плагина.
 *
 * <p>Предоставляет публичный API для создания, загрузки, удаления и телепортации
 * между мирами. Все создаваемые и загружаемые миры используют void-генератор —
 * ландшафт не генерируется, существующие чанки сохраняются как есть,
 * новые чанки остаются пустыми.
 *
 * <p><b>Управляемость мира:</b> мир считается управляемым, если его имя
 * присутствует в постоянном хранилище плагина. Управляемые миры:
 * <ul>
 *   <li>автоматически загружаются при старте сервера через {@link #reloadAll()}</li>
 *   <li>попадают под действие слушателей отключения физики</li>
 *   <li>имеют принудительно выставленные игровые правила
 *       ({@code RANDOM_TICK_SPEED=0} и т.д.)</li>
 * </ul>
 *
 * <p><b>Ограничение потока:</b> все методы интерфейса, включая предикаты
 * {@link #isManaged(World)} и {@link #isManaged(String)}, должны вызываться
 * из главного серверного потока. Внутренний кэш управляемых миров не
 * потокобезопасен — это приемлемо, так как Bukkit-события и команды
 * исполняются в главном потоке.
 *
 * @see ManagedWorld
 */
public interface EmptyWorldService {

    /**
     * Создаёт новый пустой мир с указанным именем и сохраняет его как управляемый.
     *
     * <p>Создание выполняется через {@code Bukkit.createWorld} с void-генератором
     * и отключённой генерацией структур. После успешного создания мир добавляется
     * в постоянное хранилище плагина, и к нему применяются правила тишины.
     *
     * @param name имя создаваемого мира; непустое, без разделителей пути
     * @return описание успешно созданного мира
     * @throws InvalidWorldNameException   если имя пустое или содержит запрещённые символы
     * @throws WorldAlreadyExistsException если мир с таким именем уже существует
     */
    ManagedWorld create(String name);

    /**
     * Берёт существующий мир с диска под управление плагина.
     *
     * <p>Используется, когда папка мира уже присутствует на файловой системе
     * сервера (импортирована извне или создана другим плагином). Существующие
     * чанки сохраняются как есть, но любые новые чанки, к которым обратится
     * сервер, генерируются пустыми.
     *
     * <p><b>Защита от усыновления не-миров:</b> метод требует, чтобы в директории
     * присутствовал файл-маркер {@code level.dat}. Это отсекает попытки передать
     * имя служебной папки контейнера ({@code plugins/}, {@code logs/},
     * {@code cache/} и т.п.) — такие каталоги существуют, но мирами не являются,
     * и позволить Bukkit писать в них region-файлы было бы разрушительно.
     *
     * <p><b>Защита от конфликта с уже загруженным миром:</b> если Bukkit уже
     * держит мир с таким именем (в том числе основной мир сервера), метод
     * откажется его «усыновлять» — иначе последующий {@link #delete(String)}
     * снёс бы чужую директорию.
     *
     * @param name имя существующего мира (совпадает с именем директории)
     * @return описание загруженного мира
     * @throws InvalidWorldNameException   если имя пустое или содержит запрещённые символы
     * @throws WorldNotFoundException      если папка мира не существует
     *                                     или не содержит {@code level.dat}
     * @throws WorldAlreadyExistsException если мир уже управляется плагином
     *                                     или уже загружен Bukkit независимо
     */
    ManagedWorld load(String name);

    /**
     * Удаляет управляемый мир: выгружает его, удаляет с диска и из хранилища.
     *
     * <p>Последовательность: эвакуация игроков в основной мир сервера,
     * {@code Bukkit.unloadWorld} без сохранения, рекурсивное удаление
     * директории мира, удаление записи из хранилища.
     *
     * <p><b>Partial failure:</b> если рекурсивное удаление упадёт в середине,
     * мир уже выгружен из памяти сервера, но запись в хранилище не удалена.
     * После рестарта {@link #reloadAll()} увидит отсутствие папки и пропустит
     * мир с предупреждением — ручное вмешательство не требуется.
     *
     * @param name имя удаляемого мира
     * @throws InvalidWorldNameException если имя пустое или содержит запрещённые символы
     * @throws WorldNotFoundException    если мир не управляется плагином
     * @throws WorldDeletionException    если выгрузка или удаление с диска не удались
     */
    void delete(String name);

    /**
     * Телепортирует игрока в управляемый мир в центр координат на высоту
     * {@code VoidChunkGenerator.DEFAULT_SPAWN_HEIGHT}.
     *
     * <p>Если мир числится управляемым, но в данный момент не загружен в память
     * сервера, метод сначала подгружает его через void-генератор и применяет
     * правила тишины.
     *
     * <p><b>Внимание:</b> в пустом мире по координатам назначения блоков нет —
     * игрок начнёт падать в void сразу после телепортации. Это ожидаемо для
     * плагина «песочница для создания карт»: администратор заранее переключается
     * в creative/spectator или использует {@code /fly}.
     *
     * @param player    игрок, которого нужно телепортировать
     * @param worldName имя целевого мира
     * @throws InvalidWorldNameException если имя пустое или содержит запрещённые символы
     * @throws WorldNotFoundException    если мир не управляется плагином
     */
    void teleport(Player player, String worldName);

    /**
     * Возвращает список всех управляемых миров в порядке их добавления.
     *
     * <p>Возвращаемая коллекция — неизменяемая копия текущего состояния;
     * последующие изменения хранилища в результате не отражаются.
     *
     * @return неизменяемый список описаний управляемых миров;
     *         пустой список, если управляемых миров нет
     */
    List<ManagedWorld> listManaged();

    /**
     * Проверяет, управляется ли указанный мир плагином.
     *
     * <p>Быстрый {@code O(1)} предикат для использования в слушателях
     * событий физики — выполняется на каждом тике десятки раз.
     *
     * @param world проверяемый мир; {@code null} трактуется как {@code false}
     * @return {@code true}, если мир управляется плагином
     */
    boolean isManaged(@Nullable World world);

    /**
     * Проверяет по имени, управляется ли мир плагином.
     *
     * <p>Overload для сценариев, где объект {@link World} ещё не доступен —
     * например, при вызове {@code getDefaultWorldGenerator} до загрузки мира.
     *
     * @param name имя проверяемого мира; {@code null} трактуется как {@code false}
     * @return {@code true}, если мир с таким именем присутствует в хранилище
     */
    boolean isManaged(@Nullable String name);

    /**
     * Подгружает в память сервера все миры из хранилища, ещё не загруженные.
     *
     * <p>Вызывается один раз при старте плагина. Для каждого мира из хранилища:
     * если он уже загружен — просто повторно применяет правила тишины;
     * если нет — создаёт {@code WorldCreator} с void-генератором и загружает.
     * Миры, отсутствующие на диске, пропускаются с предупреждением в лог.
     */
    void reloadAll();
}
